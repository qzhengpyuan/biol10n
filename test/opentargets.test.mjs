import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";

const root = path.dirname(fileURLToPath(import.meta.url));
const srcEngine = fs.readFileSync(path.join(root, "../src/engine.js"), "utf8");
const createEngine = new Function(srcEngine + "; return createEngine;")();
const book = JSON.parse(fs.readFileSync(path.join(root, "../dict/opentargets.json"), "utf8"));

const sites = JSON.parse(fs.readFileSync(path.join(root, "../config/sites.json"), "utf8")).sites;
const registered = sites.find((s) => s.id === "opentargets");
// sites.json 尚未登记 Open Targets 时，按推荐条目构造站点配置（dicts 顺序与建议一致）
const site =
  registered ||
  {
    id: "opentargets",
    name: "Open Targets Platform",
    hosts: ["platform.opentargets.org"],
    dicts: ["common", "spa", "opentargets"],
    scope: "body",
    spa: true,
    waitFor: "#root"
  };

const dictIds = site.dicts || ["common", "spa", "opentargets"];
const books = dictIds
  .filter((id) => fs.existsSync(path.join(root, "../dict", id + ".json")))
  .map((id) => JSON.parse(fs.readFileSync(path.join(root, "../dict", id + ".json"), "utf8")));
// 站点实际加载的栈（本册接入后就是 common + spa + opentargets），合并后才是页面真实行为
const all = { exact: {}, rules: [], templates: [] };
for (const b of books) {
  Object.assign(all.exact, b.exact || {});
  all.rules.push(...(b.rules || []));
  all.templates.push(...(b.templates || []));
}

function run(html) {
  const dom = new JSDOM(html, { url: "https://platform.opentargets.org/" });
  const engine = createEngine({ document: dom.window.document, window: dom.window, data: all, site });
  engine.start();
  return dom.window.document;
}
const text = (el) => el.textContent.replace(/\s+/g, " ").trim();

test("词库结构：条数、键值形态、规则可编译、模板槽位连续", () => {
  assert.equal(book.meta.family, "opentargets");
  assert.ok(book.meta.sites.includes("platform.opentargets.org"));
  assert.ok(Object.keys(book.exact).length >= 250, "exact 至少 250 条");
  assert.ok(book.rules.length >= 15, "rules 至少 15 条");
  assert.ok(book.templates.length >= 20, "templates 至少 20 条");

  const seen = new Set();
  for (const [k, v] of Object.entries(book.exact)) {
    assert.ok(!/[\u4e00-\u9fff]/.test(k), "键里不能有中文: " + k);
    assert.ok(/[\u4e00-\u9fff]/.test(v), "译文里必须有中文: " + k);
    assert.notEqual(k, v, "自映射: " + k);
    assert.equal(k, k.trim(), "键首尾不能有空白: " + JSON.stringify(k));
    assert.equal(v, v.trim(), "译文首尾不能有空白: " + k);
    assert.ok(!seen.has(k), "重复键: " + k);
    seen.add(k);
  }
  for (const r of book.rules) {
    const re = new RegExp(r.re);
    assert.ok(re.source.length > 0);
    assert.ok(/[\u4e00-\u9fff]/.test(r.to), "规则译文里必须有中文: " + r.re);
    if (/\(/.test(r.re)) assert.ok(/\$\d/.test(r.to), "带捕获组的规则要用到占位符: " + r.re);
  }
  for (const t of book.templates) {
    const used = [...t.pat.matchAll(/\{\{(\d+)\}\}/g)].map((m) => Number(m[1]));
    assert.ok(used.length >= 1, "模板要带槽位: " + t.pat);
    const sorted = used.slice().sort((a, b) => a - b);
    sorted.forEach((n, i) => assert.equal(n, i + 1, "槽位必须从 1 连续: " + t.pat));
    const zhUsed = [...t.zh.matchAll(/\{\{(\d+)\}\}/g)].map((m) => Number(m[1]));
    assert.deepEqual(zhUsed.slice().sort((a, b) => a - b), sorted, "译文槽位要与原文一致: " + t.pat);
  }
});

