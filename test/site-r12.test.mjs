// 检查方 r12 回归：落地页静态文案
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";

const root = path.dirname(fileURLToPath(import.meta.url));
const srcEngine = fs.readFileSync(path.join(root, "../src/engine.js"), "utf8");
const createEngine = new Function(srcEngine + "; return createEngine;")();
const load = (n) => JSON.parse(fs.readFileSync(path.join(root, "../dict", n + ".json"), "utf8"));

function boot(dicts, html) {
  const dom = new JSDOM(html);
  const exact = {};
  let rules = [];
  for (const d of [].concat(dicts)) {
    const c = load(d);
    Object.assign(exact, c.exact || {});
    if (c.rules) rules = rules.concat(c.rules);
  }
  const engine = createEngine({
    document: dom.window.document,
    window: dom.window,
    data: { exact, rules },
    site: { scope: "", block: "pre, code", attrs: [] }
  });
  engine.start();
  return dom.window.document;
}

test("HPA 首页入口卡片与新闻整段翻译", () => {
  const doc = boot("hpa", [
    '<div class="atlas_desc"><a>RNA and protein profiles in tissues and cells, based on single cell, bulk and DVP</a></div>',
    '<div class="atlas_desc">Spatial, subcellular protein profiles in human cells based on antibodies</div>',
    '<div class="newstext"><a>The Human Protein Atlas launches version 26, presenting four new resources, extensive additional data and AI tools to help researchers explore human biology and disease.</a></div>'
  ].join(""));
  assert.equal(doc.querySelectorAll(".atlas_desc")[0].textContent, "基于单细胞、批量与 DVP 的组织与细胞 RNA 和蛋白质图谱");
  assert.equal(doc.querySelectorAll(".atlas_desc")[1].textContent, "基于抗体的细胞内空间与亚细胞蛋白质图谱");
  assert.match(doc.querySelector(".newstext").textContent, /^人类蛋白质图谱发布第 26 版/);
});

test("GTEx 首页长段翻译", () => {
  const doc = boot("gtex", '<p>The Adult GTEx project is a comprehensive resource of WGS, RNA-Seq, and QTL data from samples collected from 54 non-diseased tissue sites across ~1000 adult individuals.</p>');
  assert.match(doc.querySelector("p").textContent, /^成人 GTEx 项目是一个综合性资源/);
});

test("KEGG 首页说明段翻译", () => {
  const doc = boot("kegg", '<div class="bor1">KEGG is a database resource for understanding high-level functions and utilities of biological systems, such as cells, organisms, ecosystems and the biosphere from molecular-level information, especially large-scale molecular datasets generated by genome sequencing and other high-throughput experimental technologies.</div>');
  assert.match(doc.querySelector("div").textContent, /^KEGG 是一个数据库资源/);
});

test("NCBI 页脚 Bookshelf 翻译", () => {
  const doc = boot("ncbi", '<a class="literature-footer-link">Bookshelf</a>');
  assert.equal(doc.querySelector("a").textContent, "书架");
});
